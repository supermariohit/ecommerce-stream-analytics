INSERT INTO ecommerce.users (user_id, name, city, segment, registered_at)
SELECT
    number + 1 AS user_id,
    concat('user_', toString(number + 1)) AS name,
    ['Москва','Санкт-Петербург','Новосибирск','Екатеринбург','Казань','Владивосток','Краснодар','Нижний Новгород'][1 + (number % 8)] AS city,
    ['new','regular','vip'][1 + (number % 3)] AS segment,
    now() - INTERVAL (number % 365) DAY AS registered_at
FROM numbers(100);